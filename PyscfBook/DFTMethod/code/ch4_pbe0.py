# Розрахунок енергії метану з гібридним функціоналом PBE0
# ============================================================

from pyscf import gto, dft

# Молекула метану
mol = gto.M(
    atom="C 0 0 0; H 0 0 1.089; H 1.026 0 -0.363; H -0.513 -0.889 -0.363; H -0.513 0.889 -0.363",
    basis="def2-tzvp",
    spin=0
)

# Гібридний DFT-розрахунок PBE0
mf = dft.RKS(mol)
mf.xc = "pbe0"
mf.verbose = 4

energy_pbe0 = mf.kernel()
print(f"\nЕнергія CH4 (PBE0): {energy_pbe0:.8f} Ha")

