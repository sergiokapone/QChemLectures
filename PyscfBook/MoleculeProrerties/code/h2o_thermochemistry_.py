# ============================================================
# h2o_thermochemistry.py
# Термохімічний аналіз молекули H2O
# ============================================================

from pyscf import gto, scf, hessian
from pyscf.hessian import thermo

import numpy as np

# --- Фізичні константи ---
k_B = 1.380649e-23      # Дж/К
h = 6.62607015e-34      # Дж·с
R = 8.314462618          # Дж/(моль·К)
N_A = 6.02214076e23
c = 2.99792458e10        # см/с
Ha_to_Jmol = 2625.499639 # 1 Ha = 2625.5 кДж/моль
Ha_to_kcal = 627.509
atm_to_Pa = 101325
J_to_kcal = 1/4184

T = 298.15
p = atm_to_Pa

# ------------------------------------------------------------
# Геометрія молекули
# ------------------------------------------------------------
mol = gto.M(
    atom="""
    O  0.0000  0.0000  0.1173
    H  0.0000  0.7572 -0.4692
    H  0.0000 -0.7572 -0.4692
    """,
    basis="6-31g",
    unit="angstrom",
)

print("=" * 65)
print("ТЕРМОХІМІЧНИЙ АНАЛІЗ МОЛЕКУЛИ H2O")
print("=" * 65)

# ------------------------------------------------------------
# SCF розрахунок
# ------------------------------------------------------------
mf = scf.RHF(mol)
E_elec = mf.kernel()
print(f"\nЕлектронна енергія (SCF): {E_elec:.6f} Ha = {E_elec*Ha_to_kcal:.2f} ккал/моль")

# ------------------------------------------------------------
# Гессіан і частоти
# ------------------------------------------------------------
H = mf.Hessian().kernel()
freqs = np.real(freqs[freqs > 0])  # дійсні додатні частоти

# ------------------------------------------------------------
# Нульова коливальна енергія
# ------------------------------------------------------------
E_ZPE_kcal = 0.5 * np.sum(freqs) * (h * c * N_A / 4184) / 1000
E_ZPE = E_ZPE_kcal / Ha_to_kcal

print("\nНульова коливальна енергія (ZPE):")
print(f"  Σ (1/2 ħω_i) = {E_ZPE:.6f} Ha = {E_ZPE_kcal:.2f} ккал/моль")

# ------------------------------------------------------------
# Моменти інерції для обертального внеску (ручний розрахунок)
# ------------------------------------------------------------
coords = mol.atom_coords(unit='Bohr')               # координати атомів у bohr
masses = mol.atom_mass_list() * 1.66053906660e-27   # маси в кг
m_total = np.sum(masses)

# Центр мас
r_cm = np.sum(coords.T * masses, axis=1) / m_total
coords_cm = coords - r_cm

# Тензор інерції
I_tensor = np.zeros((3, 3))
for i in range(len(masses)):
    x, y, z = coords_cm[i]
    m = masses[i]
    I_tensor += m * np.array([
        [y**2 + z**2, -x*y, -x*z],
        [-x*y, x**2 + z**2, -y*z],
        [-x*z, -y*z, x**2 + y**2]
    ])

# Власні значення (моменти інерції, кг·м²)
I = np.linalg.eigvalsh(I_tensor)

sigma = 2  # число симетрії H2O
masses = mol.atom_mass_list() * 1.66053906660e-27  # кг
m_total = np.sum(masses)

# ------------------------------------------------------------
# Ентропія та теплові внески
# ------------------------------------------------------------
theta_v = (h * c * freqs) / k_B  # коливальні температури

# 1. Трансльована складова
S_trans = R * (np.log(((2*np.pi*m_total*k_B*T)**1.5 * k_B*T) / (h**3 * p)) + 2.5)
E_trans = 1.5 * R * T / Ha_to_Jmol

# 2. Обертальна складова (нелінійна молекула)
S_rot = R * (np.log(np.sqrt(np.pi)/sigma * ((8*np.pi**2*k_B*T/h**2)**1.5)*np.sqrt(np.prod(I))) + 1.5)
E_rot = 1.5 * R * T / Ha_to_Jmol

# 3. Коливальна складова
S_vib = R * np.sum((theta_v/T)/(np.exp(theta_v/T)-1) - np.log(1-np.exp(-theta_v/T)))
E_vib = np.sum((h*c*freqs*N_A/4184)/1000 / (np.exp(theta_v/T)-1)) / Ha_to_kcal

# Повна ентропія
S_tot = S_trans + S_rot + S_vib
S_tot_cal = S_tot / 4.184  # кал/(моль·K)

# ------------------------------------------------------------
# Повні термодинамічні функції
# ------------------------------------------------------------
E_tot = E_elec + E_ZPE + E_vib + E_rot + E_trans
H_tot = E_tot + R*T/Ha_to_Jmol  # H = U + RT
G_tot = H_tot - T*(S_tot/Ha_to_Jmol)

# ------------------------------------------------------------
# Вивід результатів
# ------------------------------------------------------------
print("\nКомпоненти внутрішньої енергії при 298.15 K:")
print(f"  Коливальна E_vib = {E_vib:.6f} Ha ({E_vib*Ha_to_kcal:.2f} ккал/моль)")
print(f"  Обертальна E_rot = {E_rot:.6f} Ha ({E_rot*Ha_to_kcal:.2f} ккал/моль)")
print(f"  Поступальна E_trans = {E_trans:.6f} Ha ({E_trans*Ha_to_kcal:.2f} ккал/моль)")
print(f"  Нульова коливальна ZPE = {E_ZPE:.6f} Ha ({E_ZPE*Ha_to_kcal:.2f} ккал/моль)")

print("\nТермохімічні функції при 298.15 K:")
print(f"  Внутрішня енергія U(T):  {E_tot:.6f} Ha  ({E_tot*Ha_to_kcal:.2f} ккал/моль)")
print(f"  Ентальпія H(T):          {H_tot:.6f} Ha  ({H_tot*Ha_to_kcal:.2f} ккал/моль)")
print(f"  Вільна енергія Гіббса G(T): {G_tot:.6f} Ha  ({G_tot*Ha_to_kcal:.2f} ккал/моль)")
print(f"  Ентропія S(T):            {S_tot_cal:.2f} кал/(моль·K)")

# ------------------------------------------------------------
# Розклад ZPE по модах
# ------------------------------------------------------------
print("\nРозклад ZPE по модах (для частот >100 см⁻¹):")
for i, freq in enumerate(freqs):
    if freq > 100:
        zpe_mode_kcal = 0.0014295 * freq
        print(f"  Мода {i+1:2d}: {freq:8.1f} см⁻¹ → ZPE = {zpe_mode_kcal:5.2f} ккал/моль")

print("=" * 65)

